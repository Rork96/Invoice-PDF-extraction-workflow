#!/usr/bin/env python3
"""Renders results from eval/*.json only. No literal metrics in this file."""
import json, os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda n: json.load(open(f"{R}/eval/{n}"))
man = json.load(open(f"{R}/data/recorded/manifest.json"))
def block(title, e):
    s = f"**{title}** — _{e['source']}_\n\n| field | correct | of | accuracy |\n|---|---|---|---|\n"
    s += "".join(f"| {f} | {v['correct']} | {v['of']} | {v['accuracy_pct']}% |\n" for f, v in e["fields"].items())
    s += f"| **routing** | {e['routing']['correct']} | {e['routing']['of']} | |\n| **failure_code** | {e['failure_code']['correct']} | {e['failure_code']['of']} | |\n"
    s += f"| **all fields** | {e['all_fields']['correct']} | {e['all_fields']['of']} | |\n"
    return s
e, l, t = J("eval.json"), J("eval_live.json"), J("tests.json")
nl, ns = sum(v == "live" for v in man.values()), sum(v == "stub" for v in man.values())
md = (f"_Generated by `make showcase` from eval/eval.json, eval/eval_live.json, eval/tests.json._\n\n"
      f"Recorded LLM outputs: {nl} live (Gemini), {ns} stub (problem files 05, 08, built from ground truth; not live).\n\n"
      + block("A. Replay (all files)", e) + "\n" + block("B. Live n8n run export", l)
      + f"\n**Validator tests:** {t['passed']}/{t['total']} passed (`eval/tests.json`)\n")
open(f"{R}/docs/showcase/results.md", "w").write(md)
p = f"{R}/README.md"; s = open(p).read()
s = re.sub(r"<!-- RESULTS -->.*<!-- /RESULTS -->", lambda m: f"<!-- RESULTS -->\n{md}<!-- /RESULTS -->", s, flags=re.S) if "<!-- RESULTS -->" in s else s
open(p, "w").write(s); print(md)
